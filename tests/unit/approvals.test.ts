import { describe, expect, it } from 'vitest';
import { applyAnswer, approveBundle, approvedDownload, approvalMatches, buildBundle } from '../../src/core/index.ts';
import type { Bundle } from '../../src/core/index.ts';
import { MemoryStore } from '../../src/store/MemoryStore.ts';
import type { Store } from '../../src/store/Store.ts';
import { resolvedDemo } from '../gate/helpers.ts';
import { TEST_LOCK } from './m3Helpers.ts';
const opts = {lock:TEST_LOCK};
async function setup(): Promise<{store:MemoryStore;bundle:Bundle}> {
  const store = new MemoryStore({idGen:()=>'invented-matter'}), matter = await store.createMatter();
  const state = await resolvedDemo(); await store.saveState(matter.id,state);
  const b = buildBundle(state,{...opts,matterId:matter.id}); if (!b.ok) throw new Error(b.reasons.join(','));
  return {store,bundle:b.bundle};
}
describe('M4 approval and download binding (source only)', () => {
  it('rejects zero and nonexistent persisted revisions without adding approvals, then accepts the saved current bundle', async () => {
    const store = new MemoryStore({idGen:()=>'invented-matter'}), matter = await store.createMatter();
    const record = {matter_id:matter.id,revision:0,bundle_digest:'a'.repeat(64),library_hash:'b'.repeat(64),approver:'Demo user',approved_at:'2026-10-24T12:00:00.000Z'};
    for (const revision of [0,1]) {
      await expect(store.appendApproval({...record,revision})).rejects.toMatchObject({code:'invalid'});
      expect(await store.listApprovals(matter.id)).toEqual([]);
    }
    const state = await resolvedDemo(); await store.saveState(matter.id,state);
    await expect(store.appendApproval({...record,revision:state.revision+1})).rejects.toMatchObject({code:'invalid'});
    expect(await store.listApprovals(matter.id)).toEqual([]);
    const built = buildBundle(state,{...opts,matterId:matter.id}); if (!built.ok) throw new Error(built.reasons.join(','));
    const approval = await approveBundle(store,matter.id,built.bundle,'Demo user',opts);
    expect(approval.revision).toBe(state.revision);
    expect(await store.listApprovals(matter.id)).toEqual([approval]);
  });
  it('requires approval, appends a bound approval and serves exactly the approved regenerated bytes', async () => {
    const {store,bundle} = await setup();
    await expect(approvedDownload(store,'invented-matter',bundle,'agreement.md',opts)).rejects.toMatchObject({code:'approval_required'});
    const a = await approveBundle(store,'invented-matter',bundle,'Demo user',{...opts,clock:()=>'2026-10-24T12:00:00.000Z'});
    expect(a).toMatchObject({revision:bundle.manifest.revision,bundle_digest:bundle.digest,library_hash:bundle.manifest.library_hash,approved_at:'2026-10-24T12:00:00.000Z'});
    for (const name of ['agreement.md','agreement.docx','provenance.json','bundle.json'] as const) {
      const bytes = await approvedDownload(store,'invented-matter',bundle,name,opts);
      expect(bytes).toEqual(bundle.files[name]); expect(bytes).not.toBe(bundle.files[name]);
      bytes[0] ^= 1;
      expect(await approvedDownload(store,'invented-matter',bundle,name,opts)).toEqual(bundle.files[name]);
    }
    expect(approvalMatches(a,bundle,'invented-matter',bundle.manifest.revision)).toBe(true);
    expect(approvalMatches(a,bundle,'other',bundle.manifest.revision)).toBe(false);
    expect(approvalMatches({...a,library_hash:'0'.repeat(64)},bundle,'invented-matter',bundle.manifest.revision)).toBe(false);
  });
  it('regenerates on reload without extractor invocation and reproduces the approved digest', async () => {
    const {store,bundle} = await setup();
    await approveBundle(store,'invented-matter',bundle,'Demo user',opts);
    const persisted = await store.getState('invented-matter',bundle.manifest.revision); if (!persisted) throw new Error('state');
    const reload = buildBundle(persisted,{...opts,matterId:'invented-matter'}); if (!reload.ok) throw new Error('bundle');
    expect(reload.bundle.digest).toBe(bundle.digest);
    expect(await approvedDownload(store,'invented-matter',reload.bundle,'agreement.docx',opts)).toEqual(bundle.files['agreement.docx']);
  });
  it('invalidates old approvals on revision bump and requires fresh approval of the new digest', async () => {
    const {store,bundle} = await setup(); await approveBundle(store,'invented-matter',bundle,'Demo user',opts);
    const s = await store.getState('invented-matter'); if (!s) throw new Error('state');
    const edited = applyAnswer(s,'q.monthly_rent.v1',{kind:'text',text:'£1,250'}); if (!edited.ok) throw new Error('answer');
    await store.saveState('invented-matter',edited.state);
    await expect(approvedDownload(store,'invented-matter',bundle,'agreement.docx',opts)).rejects.toMatchObject({code:'stale_revision'});
    await expect(approveBundle(store,'invented-matter',bundle,'Demo user',opts)).rejects.toMatchObject({code:'stale_revision'});
    const next = buildBundle(edited.state,{...opts,matterId:'invented-matter'}); if (!next.ok) throw new Error('bundle');
    expect(next.bundle.digest).not.toBe(bundle.digest);
    await expect(approvedDownload(store,'invented-matter',next.bundle,'agreement.md',opts)).rejects.toMatchObject({code:'approval_required'});
    await approveBundle(store,'invented-matter',next.bundle,'Demo user',opts);
    expect(await approvedDownload(store,'invented-matter',next.bundle,'agreement.md',opts)).toEqual(next.bundle.files['agreement.md']);
    expect((await store.listApprovals('invented-matter')).length).toBe(2);
  });
  it('rejects mutated retained files, missing state, other-matter bundles and changed pinned content', async () => {
    const {store,bundle} = await setup(); await approveBundle(store,'invented-matter',bundle,'Demo user',opts);
    const altered = { ...bundle,files:{...bundle.files,'agreement.docx':bundle.files['agreement.docx'].slice()} }; altered.files['agreement.docx'][100] ^= 1;
    await expect(approvedDownload(store,'invented-matter',altered,'agreement.docx',opts)).rejects.toMatchObject({code:'gate_failed'});
    await expect(approveBundle(store,'other',bundle,'Demo user',opts)).rejects.toMatchObject({code:'gate_failed'});
    const missing: Store = { ...store, getState:async()=>null } as Store;
    await expect(approvedDownload(missing,'invented-matter',bundle,'agreement.md',opts)).rejects.toMatchObject({code:'missing_state'});
    await expect(approvedDownload(store,'invented-matter',bundle,'agreement.md',{lock:{status:'UNLOCKED',note:'new version'}})).rejects.toMatchObject({code:'gate_failed'});
  });
  it('rechecks a revision race and refuses stale direct appendApproval', async () => {
    const {store,bundle} = await setup(); const a = await approveBundle(store,'invented-matter',bundle,'Demo user',opts);
    const s = await store.getState('invented-matter'); if (!s) throw new Error('state');
    let reads = 0;
    const racing = { getState:async()=> (++reads > 1 ? {...s,revision:s.revision+1}:s), listApprovals:()=>store.listApprovals('invented-matter'), appendApproval:(record:typeof a)=>store.appendApproval(record) };
    await expect(approvedDownload(racing,'invented-matter',bundle,'agreement.md',opts)).rejects.toMatchObject({code:'stale_revision'});
    await expect(store.appendApproval({...a,revision:a.revision-1})).rejects.toMatchObject({code:'invalid'});
    await expect(store.appendApproval({...a,bundle_digest:'fake'})).rejects.toMatchObject({code:'invalid'});
  });
});
